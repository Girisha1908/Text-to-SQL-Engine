import { FormEvent, useState } from 'react'
import { Link } from 'react-router-dom'
import { ApiError } from '../services/api'
import { ask, AskResponse, Clarification, ResolvedTerm } from '../services/askApi'

const EXAMPLES = [
  "Show me last month's best customer.",
  'How many new customers signed up last month?',
  'What was our best-selling product last month?',
  'How many active customers do we have?',
  'Which payment method brought in the most money last month?',
]

function formatCell(v: unknown): string {
  if (typeof v === 'number') return v.toLocaleString(undefined, { maximumFractionDigits: 2 })
  if (v === null || v === undefined) return '—'
  return String(v)
}

function ClarificationCard({
  items,
  picked,
  onPick,
  onSubmit,
  busy,
}: {
  items: Clarification[]
  picked: Record<string, ResolvedTerm>
  onPick: (r: ResolvedTerm) => void
  onSubmit: () => void
  busy: boolean
}) {
  const ready = items.every((c) => picked[c.term])
  return (
    <section className="rounded-xl border border-amber-200 bg-amber-50 p-5">
      <h2 className="font-semibold text-amber-900">Before I answer — your question can be read more than one way.</h2>
      {items.map((c) => (
        <fieldset key={c.term} className="mt-4">
          <legend className="text-sm font-medium text-slate-800">{c.prompt}</legend>
          <div className="mt-2 grid gap-2 sm:grid-cols-2 lg:grid-cols-3">
            {c.options.map((o) => {
              const active = picked[c.term]?.option_id === o.id
              return (
                <button
                  key={o.id}
                  type="button"
                  onClick={() => onPick({ term: c.term, option_id: o.id, definition: o.definition })}
                  aria-pressed={active}
                  className={`rounded-lg border px-3 py-2 text-left transition ${
                    active
                      ? 'border-indigo-600 bg-white ring-2 ring-indigo-600'
                      : 'border-slate-200 bg-white hover:border-indigo-300'
                  }`}
                >
                  <span className="block text-sm font-semibold text-slate-900">{o.label}</span>
                  <span className="block text-xs text-slate-500">{o.definition}</span>
                </button>
              )
            })}
          </div>
        </fieldset>
      ))}
      <button
        type="button"
        disabled={!ready || busy}
        onClick={onSubmit}
        className="mt-5 rounded-lg bg-indigo-600 px-4 py-2 text-sm font-semibold text-white disabled:opacity-40"
      >
        {busy ? 'Answering…' : 'Answer with this meaning'}
      </button>
    </section>
  )
}

function Answer({ res }: { res: AskResponse }) {
  return (
    <section className="rounded-xl border border-slate-200 bg-white p-5 shadow-sm">
      {res.rows.length === 0 ? (
        <p className="text-sm text-slate-500">No matching data for this question.</p>
      ) : (
        <div className="overflow-x-auto">
          <table className="min-w-full text-sm">
            <thead>
              <tr className="border-b border-slate-200 text-left text-slate-500">
                {res.columns.map((c) => (
                  <th key={c} className="px-3 py-2 font-medium">
                    {c.replace(/_/g, ' ')}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {res.rows.map((r, i) => (
                <tr key={i} className="border-b border-slate-100 last:border-0">
                  {r.map((v, j) => (
                    <td key={j} className={`px-3 py-2 ${typeof v === 'number' ? 'text-right tabular-nums' : ''}`}>
                      {formatCell(v)}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
          {res.truncated && <p className="mt-2 text-xs text-slate-400">Showing the first {res.row_count} rows.</p>}
        </div>
      )}

      {res.assumptions.length > 0 && (
        <div className="mt-5">
          <h3 className="text-xs font-semibold uppercase tracking-wide text-slate-400">How I read your question</h3>
          <ul className="mt-1 list-disc space-y-0.5 pl-5 text-sm text-slate-600">
            {res.assumptions.map((a) => (
              <li key={a}>{a}</li>
            ))}
          </ul>
        </div>
      )}

      <details className="mt-4 text-sm">
        <summary className="cursor-pointer text-slate-500 hover:text-slate-700">View technical details</summary>
        <pre className="mt-2 overflow-x-auto whitespace-pre-wrap rounded-lg bg-slate-900 p-3 text-xs text-slate-100">
          {res.sql}
        </pre>
        <p className="mt-1 text-xs text-slate-400">Generated by: {res.generator}</p>
      </details>
    </section>
  )
}

export default function Ask() {
  const [question, setQuestion] = useState('')
  const [clarify, setClarify] = useState(true)
  const [res, setRes] = useState<AskResponse | null>(null)
  const [picked, setPicked] = useState<Record<string, ResolvedTerm>>({})
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string | null>(null)

  async function run(q: string, clarifications: ResolvedTerm[] = []) {
    setBusy(true)
    setError(null)
    try {
      setRes(await ask(q, clarify ? 'engine' : 'direct', clarifications))
    } catch (e) {
      setError(e instanceof ApiError ? e.message : 'Could not reach the API.')
    } finally {
      setBusy(false)
    }
  }

  function submit(e?: FormEvent, q = question) {
    e?.preventDefault()
    if (q.trim().length < 3) return
    setPicked({})
    void run(q.trim())
  }

  return (
    <div className="min-h-screen bg-slate-50 text-slate-800">
      <main className="mx-auto max-w-4xl px-4 py-10">
        <Link to="/" className="text-sm text-slate-400 hover:text-slate-600">
          ← InsightCart
        </Link>
        <h1 className="mt-2 text-3xl font-bold">Ask your data</h1>
        <p className="mt-1 text-slate-500">
          Ask about customers, orders, products and payments in plain English. If a question can mean more than one
          thing, you'll be asked which one before any query runs.
        </p>

        <form onSubmit={submit} className="mt-6 flex flex-col gap-3 sm:flex-row">
          <label htmlFor="q" className="sr-only">
            Question
          </label>
          <input
            id="q"
            value={question}
            onChange={(e) => setQuestion(e.target.value)}
            maxLength={500}
            placeholder="e.g. Show me last month's best customer."
            className="flex-1 rounded-lg border border-slate-300 bg-white px-4 py-2.5 shadow-sm focus:border-indigo-500 focus:outline-none focus:ring-2 focus:ring-indigo-200"
          />
          <button
            type="submit"
            disabled={busy || question.trim().length < 3}
            className="rounded-lg bg-indigo-600 px-5 py-2.5 font-semibold text-white disabled:opacity-40"
          >
            {busy ? 'Thinking…' : 'Ask'}
          </button>
        </form>

        <div className="mt-3 flex flex-wrap items-center gap-2">
          {EXAMPLES.map((ex) => (
            <button
              key={ex}
              type="button"
              onClick={() => {
                setQuestion(ex)
                submit(undefined, ex)
              }}
              className="rounded-full border border-slate-200 bg-white px-3 py-1 text-xs text-slate-600 hover:border-indigo-300"
            >
              {ex}
            </button>
          ))}
        </div>

        <label className="mt-4 flex items-center gap-2 text-sm text-slate-600">
          <input type="checkbox" checked={clarify} onChange={(e) => setClarify(e.target.checked)} />
          Ask me when a question is ambiguous
          <span className="text-slate-400">(turn off to see what a guess-first system would answer)</span>
        </label>

        <div className="mt-6 space-y-4" aria-live="polite">
          {error && <p className="rounded-lg bg-red-50 p-4 text-sm text-red-700">{error}</p>}
          {res?.status === 'needs_clarification' && (
            <ClarificationCard
              items={res.clarifications}
              picked={picked}
              onPick={(r) => setPicked((p) => ({ ...p, [r.term]: r }))}
              onSubmit={() => void run(res.question, Object.values(picked))}
              busy={busy}
            />
          )}
          {res?.status === 'answered' && <Answer res={res} />}
          {res && ['unsupported', 'rejected', 'error'].includes(res.status) && (
            <p className="rounded-lg bg-amber-50 p-4 text-sm text-amber-800">{res.detail}</p>
          )}
        </div>
      </main>
    </div>
  )
}
